#!/usr/bin/env python3
"""Runs all codecs on all items and writes tables and figures. See eval/README.md."""
from __future__ import annotations

import argparse
import csv
import shutil
import subprocess
import tempfile
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

import numpy as np

import metrics
import plots
import signals

DEFAULT_BITRATES = (16000, 32000, 48000, 64000, 96000)
OWN_CODECS = ("model", "baseline")
# Hard CBR for Opus, because its usual VBR mode used up to twice the target rate on tonal signals.
# The frames of this codec have a fixed budget as well.
FOREIGN_CODECS = {
    "aac": ("out.m4a", ["-c:a", "aac"]),
    "opus": ("out.opus", ["-c:a", "libopus", "-application", "audio", "-vbr", "off"]),
}
MASKING_FIGURE_BITRATE = 48000
PRE_ECHO_FIGURE = ("clicks", 48000)
VISQOL_WORKERS = 6

RESULTS_NOTE = """\
Generated by `eval/evaluate.py`. Do not edit by hand.

The excess is measured against the threshold of this codec's own model, and on the waveform. So it
favors this codec and **cannot rank it against AAC or Opus**: they follow their own models and may
replace noisy parts with synthetic noise, which counts as an error here but may sound fine. AAC is
the encoder built into ffmpeg, not the best one available. ViSQOL does not depend on this codec's
model, but it is only a prediction, here on signals unlike those it was trained on. Only listening
can settle how these codecs compare.
"""


def run(*command) -> None:
    subprocess.run([str(part) for part in command], check=True, capture_output=True)


def tool(folder: Path, name: str) -> Path:
    for candidate in (folder / name, folder / f"{name}.exe"):
        if candidate.exists():
            return candidate
    raise FileNotFoundError(f"{name} is not in {folder}")


def code_own(tools: Path, item: Path, work: Path, bitrate: int, psy: str) -> tuple[Path, int]:
    stream = work / "stream.bin"
    decoded = work / "decoded.wav"
    run(tool(tools, "codec-encode"), item, stream, "--bitrate", bitrate, "--psy", psy)
    run(tool(tools, "codec-decode"), stream, decoded)
    return decoded, stream.stat().st_size


def code_foreign(codec: str, item: Path, work: Path, bitrate: int) -> tuple[Path, int]:
    name, options = FOREIGN_CODECS[codec]
    stream = work / name
    decoded = work / "decoded.wav"
    quiet = ["ffmpeg", "-y", "-loglevel", "error"]
    run(*quiet, "-i", item, *options, "-b:a", bitrate, "-ac", 1, stream)
    run(*quiet, "-i", stream, "-c:a", "pcm_s16le", "-ar", metrics.SAMPLE_RATE, "-ac", 1, decoded)
    return decoded, stream.stat().st_size


def fitted_to(samples: np.ndarray, size: int) -> np.ndarray:
    """A decoder may return a little more or less than the input, because of its last frame."""
    if len(samples) >= size:
        return samples[:size]
    return np.concatenate([samples, np.zeros(size - len(samples))])


def measure(
    original: np.ndarray, decoded: np.ndarray, analysis: metrics.Analysis
) -> tuple[dict, np.ndarray]:
    """The noise is taken from the decoded file, so that all codecs are measured the same way."""
    noise = metrics.band_energies(metrics.mdct_frames(original - decoded), analysis.edges)
    excess = metrics.excess_db(noise, analysis.masking_threshold)
    values = {
        "snr_db": round(metrics.snr_db(original, decoded), 3),
        "segmental_snr_db": round(metrics.segmental_snr_db(original, decoded), 3),
        "mean_excess_db": round(float(np.mean(excess)), 3),
        "bands_above_percent": round(float(100 * np.mean(excess > 0)), 2),
    }
    return values, noise


def find_attack(samples: np.ndarray) -> int:
    """The first sample of the burst nearest to the middle of the signal."""
    hop = 48
    level = 0.1
    envelope = np.array(
        [np.max(np.abs(samples[i : i + hop])) for i in range(0, len(samples) - hop, hop)]
    )
    starts = np.flatnonzero((envelope[1:] > level) & (envelope[:-1] < level)) + 1
    if len(starts) == 0:
        raise ValueError("there is no burst in this signal")
    block = starts[len(starts) // 2] * hop
    return block + int(np.argmax(np.abs(samples[block : block + hop]) > level / 2))


def write_tables(folder: Path, results: list[dict], bitrates: tuple[int, ...]) -> None:
    with open(folder / "results.csv", "w", newline="", encoding="ascii") as file:
        writer = csv.DictWriter(file, fieldnames=list(results[0]), lineterminator="\n")
        writer.writeheader()
        writer.writerows(results)

    by_key = {(r["item"], r["codec"], r["bitrate"]): r for r in results}
    items = list(dict.fromkeys(row["item"] for row in results))
    codecs = list(dict.fromkeys(row["codec"] for row in results))
    lines = ["# Results", "", RESULTS_NOTE]
    sections = (
        ("Mean excess over the masking threshold in dB (lower is better)", "mean_excess_db", 2),
        ("Bands with noise above the masking threshold in percent", "bands_above_percent", 1),
        ("SNR in dB", "snr_db", 1),
        ("Segmental SNR in dB", "segmental_snr_db", 1),
        ("Bitrate actually used in kbit/s", "actual_bitrate", None),
    )
    if "visqol_mos" in results[0]:
        sections = (("ViSQOL MOS-LQO (higher is better)", "visqol_mos", 2), *sections)
    columns = " | ".join(f"{bitrate // 1000}" for bitrate in bitrates)
    for title, key, digits in sections:
        lines += [f"## {title}", "", "The columns are the target bitrates in kbit/s.", ""]
        lines += [f"| Item | Codec | {columns} |", "|---|---|" + "---:|" * len(bitrates)]
        for item in items:
            for codec in codecs:
                values = [by_key[(item, codec, bitrate)][key] for bitrate in bitrates]
                cells = [f"{v / 1000:.1f}" if digits is None else f"{v:.{digits}f}" for v in values]
                lines += [f"| {item} | {codec} | " + " | ".join(cells) + " |"]
        lines += [""]
    (folder / "results.md").write_text("\n".join(lines), encoding="ascii")


def evaluate(
    tools: Path,
    items: dict[str, Path],
    bitrates: tuple[int, ...],
    foreign: list[str],
    out: Path,
    visqol: Path | None = None,
) -> list[dict]:
    results = []
    visqol_jobs = []
    with tempfile.TemporaryDirectory() as temporary:
        work = Path(temporary)
        for name, item in items.items():
            original = metrics.read_wav(item)
            seconds = len(original) / metrics.SAMPLE_RATE
            # The thresholds depend only on the signal, so any bitrate will do.
            table = work / "analysis.csv"
            run(tool(tools, "codec-analyze"), item, table, "--bitrate", 64000)
            analysis = metrics.read_analysis(table)

            for bitrate in bitrates:
                levels = {}
                for codec in (*OWN_CODECS, *foreign):
                    if codec in OWN_CODECS:
                        psy = "on" if codec == "model" else "off"
                        decoded_path, size = code_own(tools, item, work, bitrate, psy)
                    else:
                        decoded_path, size = code_foreign(codec, item, work, bitrate)
                    decoded = fitted_to(metrics.read_wav(decoded_path), len(original))
                    values, noise = measure(original, decoded, analysis)
                    results.append(
                        {
                            "item": name,
                            "codec": codec,
                            "bitrate": bitrate,
                            "actual_bitrate": round(size * 8 / seconds),
                            **values,
                        }
                    )
                    if visqol:
                        kept = work / f"{name}_{codec}_{bitrate}.wav"
                        shutil.copy(decoded_path, kept)
                        visqol_jobs.append((results[-1], item, kept))
                    levels[codec] = plots.BandLevels(
                        codec, np.mean(noise, axis=0), values["mean_excess_db"]
                    )
                    if codec == "model" and (name, bitrate) == PRE_ECHO_FIGURE:
                        plots.plot_pre_echo(
                            out / f"pre_echo_{name}_{bitrate // 1000}k.png",
                            name,
                            bitrate,
                            original,
                            decoded,
                            find_attack(original),
                        )
                if bitrate == MASKING_FIGURE_BITRATE:
                    plots.plot_masking(
                        out / f"masking_{name}_{bitrate // 1000}k.png",
                        name.replace("_", " "),
                        bitrate,
                        analysis.edges,
                        np.mean(analysis.energy, axis=0),
                        np.mean(analysis.masking_threshold, axis=0),
                        [levels["baseline"], levels["model"]],
                    )
            print(f"{name} done", flush=True)

        # It takes seconds for each file, far longer than everything else here.
        with ThreadPoolExecutor(VISQOL_WORKERS) as pool:
            scores = pool.map(lambda job: metrics.visqol_mos(visqol, job[1], job[2]), visqol_jobs)
            for job, score in zip(visqol_jobs, scores):
                job[0]["visqol_mos"] = round(score, 3)
    return results


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--tools", type=Path, required=True, help="folder of the built tools")
    parser.add_argument("--out", type=Path, default=Path("eval/out"), help="folder for the results")
    parser.add_argument(
        "--items",
        type=Path,
        help="folder with WAV files (16 bit, 48 kHz, mono) to use instead of synthetic signals",
    )
    parser.add_argument(
        "--duration",
        type=float,
        default=signals.DURATION_SECONDS,
        help="length of the synthetic signals in seconds",
    )
    parser.add_argument(
        "--bitrates", type=int, nargs="+", default=list(DEFAULT_BITRATES), help="in bit/s"
    )
    parser.add_argument(
        "--visqol", type=Path, help="folder of ViSQOL, built by eval/build_visqol.sh, for its scores"
    )
    arguments = parser.parse_args()

    arguments.out.mkdir(parents=True, exist_ok=True)
    foreign = []
    if shutil.which("ffmpeg"):
        foreign = list(FOREIGN_CODECS)
    else:
        print("ffmpeg was not found, so the comparison with AAC and Opus is left out.")

    with tempfile.TemporaryDirectory() as temporary:
        if arguments.items:
            items = {path.stem: path for path in sorted(arguments.items.glob("*.wav"))}
            if not items:
                parser.error(f"there are no WAV files in {arguments.items}")
        else:
            items = {}
            for name in signals.ITEMS:
                items[name] = Path(temporary) / f"{name}.wav"
                signals.write_item(items[name], name, arguments.duration)

        bitrates = tuple(sorted(arguments.bitrates))
        results = evaluate(arguments.tools, items, bitrates, foreign, arguments.out, arguments.visqol)
    write_tables(arguments.out, results, bitrates)
    plots.plot_measures(arguments.out / "measures.png", results)
    if arguments.visqol:
        plots.plot_visqol(arguments.out / "visqol.png", results)
    print(f"The results are in {arguments.out}")


if __name__ == "__main__":
    main()
